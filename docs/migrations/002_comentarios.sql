-- Issue #166: tabela de comentários (base do sistema de comentários)
-- Depende de: 001_initial_schema.sql (perfis, professores, disciplinas, turmas)
-- Fora do escopo: reações, denúncia e moderação.
--
-- A mesma conta pode comentar várias vezes para o mesmo professor e disciplina.
-- A leitura pública e a escrita pelo dono seguem o escopo da issue #166.

BEGIN;

CREATE TABLE IF NOT EXISTS comentarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    UUID   NOT NULL REFERENCES perfis(id)      ON DELETE CASCADE,
    professor_id  BIGINT NOT NULL REFERENCES professores(id) ON DELETE CASCADE,
    disciplina_id BIGINT NOT NULL REFERENCES disciplinas(id) ON DELETE RESTRICT,
    texto         TEXT   NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ocultado_em   TIMESTAMPTZ,
    CONSTRAINT ck_comentarios_texto_tamanho CHECK (
        char_length(regexp_replace(texto, '^[[:space:]]+|[[:space:]]+$', '', 'g'))
        BETWEEN 2 AND 1000
    )
);

CREATE INDEX IF NOT EXISTS idx_comentarios_professor_criado
    ON comentarios (professor_id, criado_em DESC);

-- Mantém atualizado_em
CREATE OR REPLACE FUNCTION set_atualizado_em()
RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_em = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_comentarios_atualizado_em ON comentarios;
CREATE TRIGGER trg_comentarios_atualizado_em
    BEFORE UPDATE OF texto, disciplina_id ON comentarios
    FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();

-- RLS
ALTER TABLE comentarios ENABLE ROW LEVEL SECURITY;

-- Permissões por coluna: o dono não mexe em criado_em, ocultado_em etc.
REVOKE ALL ON comentarios FROM PUBLIC, anon, authenticated;
GRANT SELECT ON comentarios TO anon, authenticated;
GRANT INSERT (usuario_id, professor_id, disciplina_id, texto) ON comentarios TO authenticated;
GRANT UPDATE (texto, disciplina_id) ON comentarios TO authenticated;
GRANT DELETE ON comentarios TO authenticated;

-- Leitura pública (só comentários não ocultados; o dono vê os próprios sempre)
DROP POLICY IF EXISTS comentarios_select ON comentarios;
CREATE POLICY comentarios_select ON comentarios
    FOR SELECT TO anon, authenticated
    USING (ocultado_em IS NULL OR usuario_id = auth.uid());

-- Escrita só pelo dono, com disciplina realmente ministrada pelo professor
DROP POLICY IF EXISTS comentarios_insert ON comentarios;
CREATE POLICY comentarios_insert ON comentarios
    FOR INSERT TO authenticated
    WITH CHECK (
        usuario_id = auth.uid()
        AND EXISTS (
            SELECT 1 FROM turmas t
            WHERE t.professor_id = comentarios.professor_id
              AND t.disciplina_id = comentarios.disciplina_id
        )
    );

DROP POLICY IF EXISTS comentarios_update ON comentarios;
CREATE POLICY comentarios_update ON comentarios
    FOR UPDATE TO authenticated
    USING (usuario_id = auth.uid())
    WITH CHECK (
        usuario_id = auth.uid()
        AND EXISTS (
            SELECT 1 FROM turmas t
            WHERE t.professor_id = comentarios.professor_id
              AND t.disciplina_id = comentarios.disciplina_id
        )
    );

DROP POLICY IF EXISTS comentarios_delete ON comentarios;
CREATE POLICY comentarios_delete ON comentarios
    FOR DELETE TO authenticated
    USING (usuario_id = auth.uid());

COMMIT;
