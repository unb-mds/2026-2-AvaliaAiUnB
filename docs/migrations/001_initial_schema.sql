-- Esquema inicial do AvaliaAi UnB no Supabase (PostgreSQL)
-- Pode ser executado diretamente no SQL Editor de um projeto Supabase vazio.

-- 1. Tabela de professores (alimentada pelo scraper do SIGAA)
CREATE TABLE IF NOT EXISTS professores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    departamento VARCHAR(255) NOT NULL DEFAULT '',
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_professores_nome_departamento UNIQUE (nome, departamento)
);

-- 2. Tabela de disciplinas (alimentada pelo scraper do SIGAA)
CREATE TABLE IF NOT EXISTS disciplinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_disciplinas_codigo UNIQUE (codigo)
);

-- 3. Tabela de turmas (vínculo professor + disciplina por semestre, alimentada pelo scraper)
CREATE TABLE IF NOT EXISTS turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES professores(id) ON DELETE CASCADE,
    disciplina_id BIGINT NOT NULL REFERENCES disciplinas(id) ON DELETE CASCADE,
    ano INTEGER NOT NULL,
    periodo INTEGER NOT NULL CHECK (periodo BETWEEN 1 AND 4),
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_turmas_prof_disc_ano_periodo UNIQUE (professor_id, disciplina_id, ano, periodo)
);

-- 4. Tabela de perfis de usuários (vinculada ao Supabase Auth: auth.users)
CREATE TABLE IF NOT EXISTS perfis (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username VARCHAR(30) NOT NULL,
    nome_completo VARCHAR(100) NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_perfis_username UNIQUE (username)
);

-- 5. Tabela de avaliações por critérios objetivos (notas inteiras de 1 a 5)
CREATE TABLE IF NOT EXISTS avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id UUID NOT NULL REFERENCES perfis(id) ON DELETE CASCADE,
    professor_id BIGINT NOT NULL REFERENCES professores(id) ON DELETE CASCADE,
    disciplina_id BIGINT NOT NULL REFERENCES disciplinas(id) ON DELETE CASCADE,
    ano INTEGER NOT NULL,
    periodo INTEGER NOT NULL CHECK (periodo BETWEEN 1 AND 4),
    didatica INTEGER NOT NULL CHECK (didatica BETWEEN 1 AND 5),
    clareza INTEGER NOT NULL CHECK (clareza BETWEEN 1 AND 5),
    organizacao INTEGER NOT NULL CHECK (organizacao BETWEEN 1 AND 5),
    disponibilidade INTEGER NOT NULL CHECK (disponibilidade BETWEEN 1 AND 5),
    dificuldade INTEGER NOT NULL CHECK (dificuldade BETWEEN 1 AND 5),
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_avaliacoes_usuario_prof_disc UNIQUE (usuario_id, professor_id, disciplina_id)
);

-- 6. View consolidada de professores e disciplinas lecionadas nas turmas
CREATE OR REPLACE VIEW vw_professor_disciplina AS
SELECT
    t.id AS turma_id,
    t.professor_id,
    p.nome AS professor,
    p.departamento,
    t.disciplina_id,
    d.codigo AS codigo_disciplina,
    d.nome AS disciplina,
    t.ano,
    t.periodo
FROM turmas t
JOIN professores p ON p.id = t.professor_id
JOIN disciplinas d ON d.id = t.disciplina_id;