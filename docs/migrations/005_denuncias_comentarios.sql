-- Issue #215: denúncia de comentários (RF10, decisão C06).
-- Depende de: 002_comentarios.sql (comentarios, perfis)
-- Fora do escopo: painel do moderador (#216) e ocultação automática por número de denúncias.
--
-- A denúncia é privada: nem o autor do comentário nem visitantes leem esta tabela.
-- Só o backend (service_role) grava e consulta. Uma denúncia ativa (resolvida_em nula)
-- por usuário e comentário; depois de resolvida, a pessoa pode denunciar de novo.

BEGIN;

CREATE TABLE IF NOT EXISTS denuncias_comentarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comentario_id BIGINT NOT NULL REFERENCES comentarios(id) ON DELETE CASCADE,
    usuario_id    UUID   NOT NULL REFERENCES perfis(id)      ON DELETE CASCADE,
    motivo        TEXT   NOT NULL,
    explicacao    TEXT,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolvida_em  TIMESTAMPTZ,
    CONSTRAINT ck_denuncias_motivo CHECK (motivo IN (
        'ofensa', 'dados_pessoais', 'discriminacao', 'ameaca', 'spam', 'fora_do_tema'
    )),
    CONSTRAINT ck_denuncias_explicacao_tamanho CHECK (
        explicacao IS NULL OR char_length(explicacao) BETWEEN 1 AND 500
    )
);

-- Uma denúncia ativa por usuário e comentário
CREATE UNIQUE INDEX IF NOT EXISTS uq_denuncias_ativa_usuario_comentario
    ON denuncias_comentarios (comentario_id, usuario_id)
    WHERE resolvida_em IS NULL;

-- Fila da moderação (#216): denúncias abertas, mais antigas primeiro
CREATE INDEX IF NOT EXISTS idx_denuncias_abertas
    ON denuncias_comentarios (criado_em)
    WHERE resolvida_em IS NULL;

-- RLS sem políticas para anon/authenticated: ninguém lê nem grava pela API pública.
ALTER TABLE denuncias_comentarios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON denuncias_comentarios FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON denuncias_comentarios TO service_role;

COMMIT;
